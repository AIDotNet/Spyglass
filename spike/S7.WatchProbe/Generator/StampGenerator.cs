using System;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;

namespace S7.Generator;

[Generator]
public sealed class StampGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext ctx)
    {
        var enabled = ctx.AnalyzerConfigOptionsProvider.Select((o, _) =>
            !o.GlobalOptions.TryGetValue("build_property.SpyglassHotReloadStamps", out var v) || !string.Equals(v, "false", StringComparison.OrdinalIgnoreCase));
        var asmName = ctx.CompilationProvider.Select((c, _) => c.AssemblyName ?? "");
        var xaml = ctx.AdditionalTextsProvider
            .Combine(ctx.AnalyzerConfigOptionsProvider)
            .Where(p => p.Right.GetOptions(p.Left).TryGetValue("build_metadata.AdditionalFiles.SourceItemGroup", out var g) && g == "AvaloniaXaml")
            .Select((p, ct) => (Path: p.Left.Path, Text: p.Left.GetText(ct)?.ToString() ?? ""));
        ctx.RegisterSourceOutput(xaml.Combine(asmName).Combine(enabled), (spc, x) =>
        {
            var doc = x.Left.Left; var on = x.Right;
            if (!on) return;
            var id = Hex(Encoding.UTF8.GetBytes(doc.Path)).Substring(0, 12);
            var hash = Hex(Encoding.UTF8.GetBytes(doc.Text));
            var cls = Regex.Match(doc.Text, "x:Class\\s*=\\s*\"([^\"]+)\"").Groups[1].Value;
            var src = $$"""
                // <auto-generated/> S7 stamp for {{doc.Path}}
                namespace Spyglass.Generated
                {
                    [global::System.Runtime.CompilerServices.CreateNewOnMetadataUpdate]
                    internal static class SpyglassXamlStamp_{{id}}
                    {
                        public const string Path = @"{{doc.Path.Replace("\"", "\"\"")}}";
                        public const string Class = "{{cls}}";
                        public const string Hash = "{{hash}}";
                        public static string Text() => @"{{doc.Text.Replace("\"", "\"\"")}}";
                    }
                }
                """;
            spc.AddSource($"SpyglassXamlStamp_{id}.g.cs", src);
        });
    }

    static string Hex(byte[] data)
    {
        using var sha = SHA256.Create();
        var h = sha.ComputeHash(data); var sb = new StringBuilder();
        foreach (var b in h) sb.Append(b.ToString("x2"));
        return sb.ToString();
    }
}
