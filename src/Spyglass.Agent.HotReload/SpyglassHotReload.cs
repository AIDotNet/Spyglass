using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using System.Runtime.CompilerServices;
using Avalonia.Controls;
using Spyglass.Protocol.Messages;

namespace Spyglass.Agent.HotReload;

/// <summary>A XAML document compiled into an app assembly, as registered by the generated module initializer.</summary>
/// <param name="Path">Absolute source path at build time.</param>
/// <param name="Uri">avares:// URI.</param>
/// <param name="Class">x:Class, or null.</param>
/// <param name="Text">The document text the assembly was compiled from (the "last good" XAML before the first reload).</param>
public sealed record SpyglassXamlDocument(string Path, string Uri, string? Class, Func<string> Text);

/// <summary>
/// Entry point for code generated by Spyglass.HotReload.Generators (design/hot-reload/README.md §3, §3.1).
/// Not meant to be called by hand.
/// </summary>
public static class SpyglassHotReload
{
    static readonly object Lock = new();
    static readonly List<RegisteredDocument> Docs = [];
    static HotReloadFeature? _feature;

    /// <summary>Raised (any thread) when an assembly registers documents after a session started.</summary>
    internal static event Action? DocumentsChanged;

    /// <summary>Called from a module initializer in every assembly that references the Spyglass.HotReload package.</summary>
    [System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)]
    public static void Register(Assembly assembly, bool useCompiledBindingsByDefault, params SpyglassXamlDocument[] documents)
    {
        lock (Lock)
        {
            foreach (var d in documents)
            {
                Docs.RemoveAll(x => x.Uri == d.Uri);
                Docs.Add(new RegisteredDocument(d, assembly, useCompiledBindingsByDefault));
            }
            if (_feature is null)
            {
                _feature = new HotReloadFeature();
                SpyglassAgent.AddGlobalFeature(_feature);
            }
        }
        DocumentsChanged?.Invoke();
    }

    /// <summary>
    /// Called by the InitializeComponent that Spyglass.HotReload.Generators emits in Debug builds (design §5.1): runs the
    /// type's compiled XAML through XamlIl's trampoline, which honours the hot reload override. Resolved by reflection at
    /// run time, so it keeps working when a Hot Reload delta recompiles InitializeComponent (the direct
    /// AvaloniaXamlLoader.Load(this) call would hit a throwing stub there). False: not compiled XAML, use Load(this).
    /// </summary>
    [System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)]
    [UnconditionalSuppressMessage("Trimming", "IL2075", Justification = "Debug-only; the app's own x:Class types.")]
    public static bool Populate(object component)
    {
        var m = Trampolines.GetOrAdd(component.GetType(), t =>
            t.GetMethod("!XamlIlPopulateTrampoline", BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic));
        if (m is null) return false;
        try { m.Invoke(null, [component]); }
        catch (TargetInvocationException ex) when (ex.InnerException is not null)
        {
            System.Runtime.ExceptionServices.ExceptionDispatchInfo.Throw(ex.InnerException);
        }
        return true;
    }

    static readonly System.Collections.Concurrent.ConcurrentDictionary<Type, MethodInfo?> Trampolines = new();

    internal static IReadOnlyList<RegisteredDocument> Documents
    {
        get { lock (Lock) return Docs.ToList(); }
    }

    internal static RegisteredDocument? Find(string uriOrPath)
    {
        lock (Lock)
            return Docs.FirstOrDefault(d => SameUri(d.Uri, uriOrPath))
                ?? Docs.FirstOrDefault(d => string.Equals(d.Path, uriOrPath, PathComparison));
    }

    /// <summary>avares URIs: <see cref="Uri"/> lower-cases the host (the assembly name) when resolving relative sources.</summary>
    internal static bool SameUri(string a, string b) => string.Equals(a, b, StringComparison.OrdinalIgnoreCase);

    internal static StringComparison PathComparison =>
        OperatingSystem.IsLinux() ? StringComparison.Ordinal : StringComparison.OrdinalIgnoreCase;

    /// <summary>Why hot reload cannot run in this process, or null (design §4.6).</summary>
    internal static string? UnavailableReason()
    {
        if (!RuntimeFeature.IsDynamicCodeSupported) return "requires JIT (NativeAOT is not supported)";
        foreach (var a in AppDomain.CurrentDomain.GetAssemblies())
        {
            switch (a.GetName().Name)
            {
                case "HotAvalonia.Core": return "provided by HotAvalonia";
                case "AvaloniaUI.DiagnosticsSupport.HotReload": return "provided by Avalonia Hot Reload";
            }
        }
        return null;
    }

    internal static HotReloadManifest Manifest()
    {
        var reason = UnavailableReason();
        return new HotReloadManifest(reason is null, reason,
            Documents.Select(d => new XamlDocumentInfo(d.Uri, d.Path, d.Class, d.Assembly.GetName().Name ?? "")).ToList());
    }
}

internal sealed class RegisteredDocument(SpyglassXamlDocument doc, Assembly assembly, bool compiledBindings)
{
    public string Uri => doc.Uri;
    public string Path => doc.Path;
    public string? Class => doc.Class;
    public Assembly Assembly => assembly;
    public bool CompiledBindings => compiledBindings;
    public string CompiledText => doc.Text();

    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = "Debug-only hot reload; the type is the app's own x:Class.")]
    public Type? ClassType => Class is null ? null : assembly.GetType(Class);
}
